// ================================================================== 类型自动提升与强制转型 ==================================================================
//一、自动提升：
//自动提升遵循隐式转换原则，不需要显式语法，编译器自动完成。基本原则是：小范围类型 → 大范围类型，不会丢失数据。
//byte/short/char → int → long → float → double


//场景 A：算术运算中的提升
//当不同数值类型参与运算时，结果会自动提升为参与运算中"最大"的类型：
//byte b = 10;
//short s = 20;
//int i = 30;
//long l = 40L;
//float f = 50.5f;
//double d = 60.6;

//// 结果类型分析：
//double result = b + s + i + l + f + d;
//// byte + short → int;
//// int + int → int;
//// int + long → long;
//// long + float → float;
//// float + double → double




//场景 B：byte / short / char 的特殊处理
//这三个类型在运算时一律先提升为 int，即使两个 byte 相加也不例外
//byte a = 10;
//byte b = 20;
//// byte sum = a + b;  // ❌ 编译错误！a + b 结果是 int
//int sum = a + b;      // ✓ 必须接收为 int
//
//short s1 = 100;
//char c1 = 'A';
//// short result = s1 + c1;  // ❌ 编译错误！结果是 int
//int result = s1 + c1;       // ✓

//Q:为什么这样设计？
//A:防止溢出。byte 范围是 -128~127，两个 byte 相加很容易溢出，提升到 int 是 Java 的安全设计。




//场景 C：赋值时的自动提升（向上兼容）
