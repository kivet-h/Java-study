// ================================================================== 位运算 ==================================================================
//位运算是按位进行与、或、非和异或的运算。

//我们先来看看针对单个bit的位运算。与运算的规则是，必须两个数同时为1，结果才为1

//与运算的规则是，必须两个数同时为1，结果才为1：
//n = 0 & 0; // 0
//n = 0 & 1; // 0
//n = 1 & 0; // 0
//n = 1 & 1; // 1

//或运算的规则是，只要任意一个为1，结果就为1：
//n = 0 | 0; // 0
//n = 0 | 1; // 1
//n = 1 | 0; // 1
//n = 1 | 1; // 1

//非运算的规则是，0和1互换：
//n = ~0; // 1
//n = ~1; // 0

//异或运算的规则是，如果两个数不同，结果为1，否则为0：
//n = 0 ^ 0; // 0
//n = 0 ^ 1; // 1
//n = 1 ^ 0; // 1
//n = 1 ^ 1; // 0


//Java没有单个bit的数据类型。
//在Java中，对两个整数进行位运算，实际上就是按位对齐，然后依次对每一位进行运算。例如：
